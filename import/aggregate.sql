-- Create aggregated table
DROP TABLE IF EXISTS locations_agg_next;
CREATE TABLE locations_agg_next (
	id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name TEXT,
	searchname TEXT,
	element TEXT,
	featuretype TEXT,
	area_code bigint,
	object_ids BIGINT[],
	object_id_lowest BIGINT,
	"name:etymology" TEXT,
	"name:etymology:wikipedia" TEXT,
	"name:etymology:wikidata" TEXT,
	geom GEOGRAPHY(Geometry, 4326)
);

